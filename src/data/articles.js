export function getArticle(slug) {
  return articles.find((a) => a.slug === slug)
}

export function getArticles(slugs) {
  return slugs.map(getArticle).filter(Boolean)
}

/** Reading time (minutes) — Persian reading speed ≈ 200 wpm. */
export function readingTime(article) {
  const text = article.blocks
    .map((b) => (typeof b === 'string' ? b : b.text || (b.items || []).join(' ') || ''))
    .join(' ')
  const words = text.trim().split(/\s+/).length
  return Math.max(1, Math.round(words / 200))
}
